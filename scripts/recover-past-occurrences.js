/**
 * scripts/recover-past-occurrences.js
 * ─────────────────────────────────────────────────────────────────────────────
 * Recovery script to restore past deleted SessionOccurrences and StudentAttendance
 * records for a specific session ID.
 *
 * Usage: node scripts/recover-past-occurrences.js <sessionId> [optional-start-date-YYYY-MM-DD]
 * ─────────────────────────────────────────────────────────────────────────────
 */

require('dotenv').config();
const prisma = require('../src/config/db');

// Helpers matching occurrenceService
const getKolkataDateString = (date = new Date()) => {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Kolkata",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
};

const getKolkataDateTime = (dateStr, timeStr) =>
  new Date(`${dateStr}T${timeStr}:00+05:30`);

const getKolkataWeekday = (date) => {
  const weekdayStr = date.toLocaleDateString("en-US", { timeZone: "Asia/Kolkata", weekday: "long" });
  const weekdays = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
  return weekdays.indexOf(weekdayStr);
};

async function main() {
  const sessionId = process.argv[2];
  if (!sessionId) {
    console.error('❌ Error: Please provide a sessionId as the first argument.');
    console.error('Usage: node scripts/recover-past-occurrences.js <sessionId> [optional-start-date-YYYY-MM-DD]');
    process.exit(1);
  }

  console.log(`🔍 Fetching LiveSession info for ID: ${sessionId}...`);
  const session = await prisma.liveSession.findUnique({
    where: { id: sessionId },
    include: { trainer: true }
  });

  if (!session) {
    console.error('❌ Error: LiveSession not found in the database.');
    process.exit(1);
  }

  console.log(`✅ Found Session: "${session.title}" (Course: ${session.courseTitle || 'N/A'})`);

  // 1. Determine the start date of past occurrences
  let startDate;
  const passedDateStr = process.argv[3];
  if (passedDateStr) {
    startDate = new Date(passedDateStr);
    if (isNaN(startDate.getTime())) {
      console.error('❌ Error: Invalid start date format. Use YYYY-MM-DD.');
      process.exit(1);
    }
  } else {
    // Fallback: Check the earliest attendance record to find when students first joined
    const earliestAttendance = await prisma.attendance.findFirst({
      where: { sessionId },
      orderBy: { occurrenceDate: 'asc' }
    });

    if (earliestAttendance) {
      startDate = new Date(earliestAttendance.occurrenceDate);
      console.log(`ℹ️ Earliest student attendance found on: ${getKolkataDateString(startDate)}`);
    } else {
      startDate = new Date(session.createdAt);
      console.log(`ℹ️ No attendance records found. Using session creation date: ${getKolkataDateString(startDate)}`);
    }
  }

  // Set startDate to start of day in Kolkata
  const startKolkataStr = getKolkataDateString(startDate);
  startDate = new Date(`${startKolkataStr}T00:00:00Z`);

  // End date is yesterday (since we only want to recover past dates; today/future are generated by the normal flow)
  const todayStr = getKolkataDateString(new Date());
  const todayDate = new Date(`${todayStr}T00:00:00Z`);
  
  console.log(`🔄 Generating past occurrences from ${getKolkataDateString(startDate)} to yesterday...`);

  // Parse recurring days
  let daysArray = [];
  if (session.isRecurring && session.recurringDays) {
    if (Array.isArray(session.recurringDays)) {
      daysArray = session.recurringDays;
    } else {
      try {
        daysArray = typeof session.recurringDays === "string"
          ? JSON.parse(session.recurringDays)
          : session.recurringDays;
      } catch (e) {}
    }
    daysArray = Array.isArray(daysArray) ? daysArray.map(Number) : [];
  }

  const occurrencesToCreate = [];
  const oneDayMs = 24 * 60 * 60 * 1000;
  
  // Fetch existing occurrences to avoid duplicates
  const existingOccurrences = await prisma.sessionOccurrence.findMany({
    where: { sessionId }
  });
  const existingDates = new Set(existingOccurrences.map(o => getKolkataDateString(o.occurrenceDate)));

  // Query actual attendance dates to make sure we don't miss any date students joined
  const actualAttendanceRecords = await prisma.attendance.findMany({
    where: { sessionId },
    select: { occurrenceDate: true }
  });
  const actualAttendanceDates = new Set(actualAttendanceRecords.map(a => getKolkataDateString(a.occurrenceDate)));

  // Calculate day-by-day occurrences
  let currentIter = new Date(startDate.getTime());
  while (currentIter < todayDate) {
    const dateStr = getKolkataDateString(currentIter);
    let shouldGenerate = false;

    // Check if this date has actual student attendance (force restore)
    if (actualAttendanceDates.has(dateStr)) {
      shouldGenerate = true;
    } else if (session.isRecurring) {
      // Check if it fits the recurring days pattern
      const currentIterWeekday = getKolkataWeekday(currentIter);
      if (daysArray.length === 0 || daysArray.includes(currentIterWeekday)) {
        shouldGenerate = true;
      }
    } else {
      // Non-recurring: only create on creation date
      const createDateStr = getKolkataDateString(new Date(session.createdAt));
      if (dateStr === createDateStr) {
        shouldGenerate = true;
      }
    }

    // Check cancelled dates
    let cancelledArray = [];
    if (session.cancelledDates) {
      if (Array.isArray(session.cancelledDates)) cancelledArray = session.cancelledDates;
      else {
        try { cancelledArray = JSON.parse(session.cancelledDates); } catch (e) {}
      }
    }
    if (cancelledArray.includes(dateStr)) {
      shouldGenerate = false;
    }

    if (shouldGenerate && !existingDates.has(dateStr)) {
      const startsAt = session.startTime ? getKolkataDateTime(dateStr, session.startTime) : null;
      const endsAt = session.endTime ? getKolkataDateTime(dateStr, session.endTime) : null;

      if (startsAt && endsAt) {
        occurrencesToCreate.push({
          courseId: session.courseId || "default",
          sessionId: session.id,
          trainerId: session.trainerId,
          occurrenceDate: new Date(`${dateStr}T00:00:00Z`),
          startsAt,
          endsAt,
          status: "completed", // mark past ones as completed
        });
      }
    }

    currentIter = new Date(currentIter.getTime() + oneDayMs);
  }

  console.log(`👉 Found ${occurrencesToCreate.length} past occurrences to regenerate.`);

  let createdOccCount = 0;
  let restoredAttendanceCount = 0;

  for (const occData of occurrencesToCreate) {
    // 2. Recreate the past Occurrence record
    const occurrence = await prisma.sessionOccurrence.upsert({
      where: {
        sessionId_occurrenceDate: {
          sessionId: occData.sessionId,
          occurrenceDate: occData.occurrenceDate
        }
      },
      update: {
        startsAt: occData.startsAt,
        endsAt: occData.endsAt,
        status: "completed"
      },
      create: occData
    });
    createdOccCount++;

    const dateStr = getKolkataDateString(occurrence.occurrenceDate);

    // 3. Find matching student Attendances for this date
    const attendances = await prisma.attendance.findMany({
      where: {
        sessionId: occurrence.sessionId,
        occurrenceDate: occurrence.occurrenceDate
      }
    });

    // 4. Rebuild the StudentAttendance cascade-deleted records
    for (const att of attendances) {
      await prisma.studentAttendance.upsert({
        where: {
          occurrenceId_studentId: {
            occurrenceId: occurrence.id,
            studentId: att.studentId
          }
        },
        update: {
          status: att.status,
          firstJoinedAt: att.firstJoinedAt,
          lastJoinedAt: att.lastJoinedAt,
          joinCount: att.joinCount,
        },
        create: {
          courseId: occurrence.courseId,
          sessionId: occurrence.sessionId,
          occurrenceId: occurrence.id,
          occurrenceDate: occurrence.occurrenceDate,
          studentId: att.studentId,
          trainerId: occurrence.trainerId,
          firstJoinedAt: att.firstJoinedAt,
          lastJoinedAt: att.lastJoinedAt,
          joinCount: att.joinCount,
          status: att.status,
          source: "join_button"
        }
      });
      restoredAttendanceCount++;
    }
  }

  console.log(`\n🎉 Past Occurrences and Student Attendance recovery complete!`);
  console.log(`✅ Created Occurrences: ${createdOccCount}`);
  console.log(`✅ Restored Student Attendance links: ${restoredAttendanceCount}`);
}

main().catch(err => {
  console.error('❌ Recovery process failed:', err);
}).finally(() => {
  prisma.$disconnect();
});
